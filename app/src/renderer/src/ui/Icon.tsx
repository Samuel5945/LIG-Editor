export type IconName = keyof typeof ICON_SHAPES

/** 查表渲染用的强类型视图（图标名单源） */
export const ICONS: Record<IconName, Shape[]> = ICON_SHAPES

export interface IconProps {
  name: IconName
  /** 界面图标只允许 13/14/15 三档（空态等特殊场景可显式传其它值） */
  size?: number
  strokeWidth?: number
  className?: string
  title?: string
}

export function Icon({ name, size = 14, strokeWidth = 2, className, title }: IconProps): ReactElement {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={`shrink-0 ${className ?? ''}`}
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      aria-label={title}
    >
      {title ? <title>{title}</title> : null}
      {ICONS[name].map((s, i) => {
        if (s.d) return <path key={i} d={s.d} fill={s.fill ? 'currentColor' : 'none'} />
        if (s.pts) return <polygon key={i} points={s.pts} fill={s.fill ? 'currentColor' : 'none'} />
        if (s.cx !== undefined)
          return (
            <circle
              key={i}
              cx={s.cx}
              cy={s.cy}
              r={s.r}
              fill={s.fill ? 'currentColor' : 'none'}
              stroke={s.fill ? 'none' : 'currentColor'}
            />
          );
        return (
          <rect key={i} x={s.x} y={s.y} width={s.w} height={s.h} rx={s.rx} fill={s.fill ? 'currentColor' : 'none'} />
        );
      })}
    </svg>
  )
}

export default Icon
